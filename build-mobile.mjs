import { cp, mkdir, readdir, writeFile } from "node:fs/promises";
import { dirname, join, relative, sep } from "node:path";
import { fileURLToPath } from "node:url";

const root = dirname(fileURLToPath(import.meta.url));
const mobileDirectory = join(root, "mobile");
const vendorDirectory = join(root, "mobile", "dist", "vendor");
const CACHE_VERSION = "v4";

await mkdir(vendorDirectory, { recursive: true });
await cp(
  join(root, "node_modules", "chess.js", "dist", "esm", "chess.js"),
  join(vendorDirectory, "chess.js"),
  { force: true },
);
await cp(
  join(root, "node_modules", "chess.js", "src", "pgn.js"),
  join(vendorDirectory, "pgn.js"),
  { force: true },
);
await cp(
  join(root, "frontend", "pieces"),
  join(root, "mobile", "pieces"),
  { recursive: true, force: true },
);

const assets = await collectAssets(mobileDirectory);
await writeFile(
  join(mobileDirectory, "service-worker.js"),
  renderServiceWorker(CACHE_VERSION, assets),
);

async function collectAssets(directory) {
  const entries = (await readdir(directory, { withFileTypes: true }))
    .filter((entry) => entry.name !== "service-worker.js" && entry.name !== ".DS_Store")
    .sort((left, right) => left.name.localeCompare(right.name));
  const assets = [];

  for (const entry of entries) {
    const path = join(directory, entry.name);
    if (entry.isDirectory()) {
      assets.push(...await collectAssets(path));
    } else if (entry.isFile()) {
      assets.push(`./${relative(mobileDirectory, path).split(sep).join("/")}`);
    }
  }

  return assets;
}

function renderServiceWorker(version, assets) {
  const cachePrefix = "offline-pgn-reader-mobile-";
  const cacheName = `${cachePrefix}${version}`;
  return `/* Generated by build-mobile.mjs. Change CACHE_VERSION there for releases. */
const CACHE_PREFIX = ${JSON.stringify(cachePrefix)};
const CACHE_NAME = ${JSON.stringify(cacheName)};
const PRECACHE_URLS = ${JSON.stringify([...assets, "./service-worker.js"], null, 2)};

self.addEventListener("install", (event) => {
  event.waitUntil(
    caches.open(CACHE_NAME)
      .then((cache) => cache.addAll(PRECACHE_URLS))
      .then(() => self.skipWaiting()),
  );
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(
        keys
          .filter((key) => key.startsWith(CACHE_PREFIX) && key !== CACHE_NAME)
          .map((key) => caches.delete(key)),
      ))
      .then(() => self.clients.claim()),
  );
});

self.addEventListener("fetch", (event) => {
  const request = event.request;
  if (request.method !== "GET" || new URL(request.url).origin !== self.location.origin) return;

  if (request.mode === "navigate") {
    event.respondWith(
      fetch(request).catch(() => caches.match("./index.html").then((response) => response || Response.error())),
    );
    return;
  }

  event.respondWith(
    caches.match(request).then((response) => response || fetch(request)),
  );
});
`;
}
